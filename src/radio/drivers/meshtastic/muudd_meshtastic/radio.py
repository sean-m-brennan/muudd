"""What the driver needs from a radio. SerialRadio talks to real hardware;
FakeRadio stands in for it in tests."""
from typing import Callable, Optional, Protocol


class Radio(Protocol):
    def node_num(self) -> int: ...
    def firmware_version(self) -> str: ...
    def lora_config(self) -> dict: ...
    def channel_index(self, name: str) -> Optional[int]: ...
    def add_channel(self, name: str, psk: bytes) -> int: ...
    def set_preset(self, name: str) -> None: ...
    def send(self, payload: bytes, dest: int, portnum: int, want_ack: bool, channel_index: int,
             on_ack: Optional[Callable[[bool], None]]) -> int: ...
    def on_receive(self, cb: Callable[[dict], None]) -> None: ...
    def close(self) -> None: ...
